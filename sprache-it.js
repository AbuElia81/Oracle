const DAT_ART_IT = { il: "al", lo: "allo", la: "alla", "l'": "all'", i: "ai", le: "alle", due: "a due" };
export const bildDat_IT = i => {
  const b = BILD_IT[i];
  if (!b) return b;
  const m = b.match(/^(l'|il|lo|la|i|le|due)\s?(.*)$/);
  if (!m) return b;
  const art = DAT_ART_IT[m[1]];
  return m[1] === "l'" ? `all'${m[2]}` : `${art} ${m[2]}`;
};
